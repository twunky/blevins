import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { resolve } from 'node:path';
import { apiBaseUrl, captureDirectory, recordScenario, useIsolatedScenario } from './fixtures/invitation-scenario';

useIsolatedScenario({ tripAudienceAdult: true });

test('creator corrects current Plan facts and separate Notes survive detail, list and Home reads', async ({ page, request }) => {
  test.setTimeout(240_000);
  await recordScenario(test.info());
  const identities = (await (await request.get(`${apiBaseUrl}/api/development/identities`)).json()).identities as { accountId: string; label: string }[];
  const creator = identities.find(i => i.label.startsWith('Adult C'))!;
  const date = (offset: number) => {
    const d = new Date(); d.setDate(d.getDate() + offset);
    return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
  };
  const nav = page.getByRole('navigation', { name: 'Main navigation' });
  await page.goto('/home');
  await page.getByLabel('Active test identity').selectOption(creator.accountId);
  await nav.getByRole('link', { name: 'Activities', exact: true }).click();
  await page.getByRole('link', { name: 'Create Activity', exact: true }).click();
  await page.getByRole('navigation', { name: 'Choose activity type' }).getByRole('link', { name: /^Plan / }).click();
  await expect(page).toHaveURL(/\/plans\/new$/);
  await page.locator('#plan-activity').fill('Original past walk');
  await page.locator('#plan-date').fill(date(-2));
  await page.locator('#plan-time').fill('10:00');
  await page.locator('#plan-return-date').fill(date(-2));
  await page.locator('#plan-return-time').fill('15:00');
  await page.locator('#plan-checkin-date').fill(date(-2));
  await page.locator('#plan-checkin-time').fill('12:00');
  await page.locator('#plan-notes').fill('Keep the route note.');
  await page.locator('#plan-audience-group').check();
  await page.getByRole('button', { name: 'Create plan', exact: true }).click();
  await expect(page).toHaveURL(/\/plans\/[0-9a-f-]{36}$/);
  const itemUrl = new URL(page.url()).pathname;
  await expect(page.getByRole('heading', { name: 'Original past walk', exact: true })).toBeVisible();
  await nav.getByRole('link', { name: 'Home', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Original past walk', exact: true })).toHaveCount(0);
  await nav.getByRole('link', { name: 'Activities', exact: true }).click();
  const planFilter = page.getByRole('group', { name: 'Activity type' }).getByRole('button', { name: /^Plans / });
  await planFilter.click();
  await expect(planFilter).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('.activity-row').filter({ hasText: 'Original past walk' })).toHaveCount(0);
  await page.getByLabel('Activity dates').selectOption('all');
  await page.locator('.activity-row').filter({ hasText: 'Original past walk' }).click();
  await expect(page).toHaveURL(new RegExp(`${itemUrl}$`));
  const detail = page.getByRole('article', { name: 'Plan details' });
  await expect(detail).toContainText('Keep the route note.');
  await expect(detail.getByRole('button', { name: 'Edit note', exact: true })).toBeVisible();
  await detail.getByRole('link', { name: 'Correct activity and timing', exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`${itemUrl}/edit$`));
  const correction = page.getByRole('form', { name: 'Correct activity and timing' });
  await expect(correction.getByLabel('Activity / destination', { exact: true })).toHaveValue('Original past walk');
  await expect(correction.getByLabel('Expected return date', { exact: true })).toHaveValue(date(-2));
  await expect(correction).toContainText('It does not schedule a Check-In or send reminders.');
  await expect(correction.locator('textarea')).toHaveCount(0);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: resolve(captureDirectory('plan-correction'), 'form-1440.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await correction.getByLabel('Activity / destination', { exact: true }).fill('Corrected upcoming coast walk');
  await correction.getByLabel('Date', { exact: true }).fill(date(2));
  await correction.getByLabel('Time', { exact: true }).fill('11:30');
  await correction.getByLabel('Expected return date', { exact: true }).fill('');
  await correction.getByLabel('Expected return time', { exact: true }).fill('');
  await correction.getByLabel('Expected Check-In date', { exact: true }).fill(date(2));
  await correction.getByLabel('Expected Check-In time', { exact: true }).fill('14:00');
  await expect(detail.getByRole('button', { name: 'Edit note', exact: true })).toHaveCount(0);
  const saveResponse = page.waitForResponse(response => response.url().endsWith(`/api${itemUrl}/activity-timing`)
    && response.request().method() === 'PUT');
  await correction.getByRole('button', { name: 'Save', exact: true }).click();
  expect((await saveResponse).status()).toBe(200);
  await expect(page).toHaveURL(new RegExp(`${itemUrl}$`));
  await expect(detail.getByRole('heading', { name: 'Corrected upcoming coast walk', exact: true })).toBeVisible();
  const savedConfirmation = detail.getByRole('status').filter({ hasText: 'Plan activity and timing saved.' });
  await expect(savedConfirmation).toBeVisible();
  await expect(savedConfirmation).toHaveText('Plan activity and timing saved.');
  await expect(detail).toContainText('Keep the route note.');
  await expect(detail).not.toContainText('Expected return:');
  await page.goBack();
  await expect(page).toHaveURL(new RegExp(`${itemUrl}/edit$`));
  await expect(correction.getByLabel('Activity / destination', { exact: true })).toHaveValue('Corrected upcoming coast walk');
  await page.goForward();
  await expect(page).toHaveURL(new RegExp(`${itemUrl}$`));
  await expect(detail.getByRole('heading', { name: 'Corrected upcoming coast walk', exact: true })).toBeVisible();
  await expect(savedConfirmation).toHaveCount(0);
  await detail.getByRole('button', { name: 'Edit note', exact: true }).click();
  await expect(page.locator('#item-plan-note')).toHaveValue('Keep the route note.');
  await page.locator('#item-plan-note').fill('Keep the revised route note.');
  await detail.getByRole('button', { name: 'Save note', exact: true }).click();
  await expect(detail).toContainText('Keep the revised route note.');
  await page.reload();
  await expect(savedConfirmation).toHaveCount(0);
  await expect(detail).toContainText('Corrected upcoming coast walk');
  await expect(detail).toContainText('Keep the revised route note.');
  await detail.getByRole('link', { name: 'Correct activity and timing', exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`${itemUrl}/edit$`));
  await page.reload();
  await expect(correction.getByLabel('Date', { exact: true })).toHaveValue(date(2));
  await expect(correction.getByLabel('Time', { exact: true })).toHaveValue(/^11:30(?::00)?$/);
  await expect(correction.getByLabel('Expected return date', { exact: true })).toHaveValue('');
  await expect(correction.getByLabel('Expected Check-In date', { exact: true })).toHaveValue(date(2));
  await page.waitForLoadState('networkidle');
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({ path: resolve(captureDirectory('plan-correction'), 'form-390.png'), fullPage: true });
  await correction.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`${itemUrl}$`));
  await expect(savedConfirmation).toHaveCount(0);
  await expect(detail).toContainText('Keep the revised route note.');
  await page.getByRole('link', { name: 'Back to Activities', exact: true }).click();
  await planFilter.click();
  await expect(planFilter).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('.activity-row').filter({ hasText: 'Corrected upcoming coast walk' })).toBeVisible();
  await expect(page.locator('.activity-row').filter({ hasText: 'Original past walk' })).toHaveCount(0);
  await nav.getByRole('link', { name: 'Home', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Corrected upcoming coast walk', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Corrected upcoming coast walk', exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`${itemUrl}$`));
  await expect(detail).toContainText('Keep the revised route note.');
});
