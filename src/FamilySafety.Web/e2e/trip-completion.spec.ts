import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { resolve } from 'node:path';
import { apiBaseUrl, captureDirectory, recordScenario, useIsolatedScenario } from './fixtures/invitation-scenario';

useIsolatedScenario({ tripAudienceAdult: true });

test('creator explicitly completes a current Trip and keeps normal Notes, editing and list access', async ({ page, request }) => {
  test.setTimeout(240_000);
  await recordScenario(test.info());
  const identities = (await (await request.get(`${apiBaseUrl}/api/development/identities`)).json()).identities as { accountId: string; label: string }[];
  const creator = identities.find(i => i.label.startsWith('Adult C'))!;
  const date = (offset: number) => {
    const d = new Date(); d.setDate(d.getDate() + offset);
    return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
  };
  const title = 'Explicit completion coast Trip';
  const nav = page.getByRole('navigation', { name: 'Main navigation' });
  await page.goto('/home');
  await page.getByLabel('Active test identity').selectOption(creator.accountId);
  await nav.getByRole('link', { name: 'Plans & Trips', exact: true }).click();
  await page.getByRole('link', { name: /^Open Trips/ }).click();
  await page.getByRole('button', { name: 'Create trip', exact: true }).click();
  await page.locator('#trip-title').fill(title);
  await page.locator('#trip-destination').fill('Synthetic coast');
  await page.locator('#trip-start').fill(date(-1));
  await page.locator('#trip-end').fill(date(2));
  await page.getByRole('group', { name: /^Travelers/ }).getByRole('checkbox', { name: /Development Audience Member/ }).check();
  await page.getByRole('radio', { name: 'This Family', exact: true }).check();
  await page.locator('form.trip-form').getByRole('button', { name: 'Create trip', exact: true }).click();
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  await nav.getByRole('link', { name: 'Home', exact: true }).click();
  const currentTrips = page.locator('[aria-labelledby="home-trips-heading"]');
  await expect(currentTrips.getByRole('link', { name: title, exact: true })).toBeVisible();
  await currentTrips.getByRole('link', { name: title, exact: true }).click();
  const detailUrl = page.url();
  await expect(page.getByRole('button', { name: 'Edit trip details', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Complete Trip', exact: true }).focus();
  await page.keyboard.press('Enter');
  const confirmation = page.getByRole('group', { name: 'Complete Trip confirmation' });
  await expect(confirmation).toContainText('This Trip will be marked complete. This action cannot currently be undone.');
  await page.waitForLoadState('networkidle');
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await page.screenshot({ path: resolve(captureDirectory('trip-completion'), 'confirmation-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({ path: resolve(captureDirectory('trip-completion'), 'confirmation-390.png'), fullPage: true });
  await confirmation.getByRole('button', { name: 'Confirm completion', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: /^Completed$/ })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Complete Trip', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Change audience', exact: true })).toBeVisible();
  await page.getByLabel('Add a Note', { exact: true }).fill('Notes remain collaborative after completion.');
  await page.getByRole('button', { name: 'Add note', exact: true }).click();
  await expect(page.locator('.trip-note-list')).toContainText('Notes remain collaborative after completion.');
  await page.getByRole('button', { name: 'Edit trip details', exact: true }).click();
  await page.locator('#trip-description').fill('Details remain editable after completion.');
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(page.locator('.trip-detail')).toContainText('Details remain editable after completion.');
  await page.reload();
  await expect(page.getByRole('status').filter({ hasText: /^Completed$/ })).toBeVisible();
  await page.waitForLoadState('networkidle');
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await page.screenshot({ path: resolve(captureDirectory('trip-completion'), 'completed-390.png'), fullPage: true });
  await nav.getByRole('link', { name: 'Home', exact: true }).click();
  await expect(currentTrips).toBeVisible();
  await expect(currentTrips.getByRole('link', { name: title, exact: true })).toHaveCount(0);
  await currentTrips.getByRole('button', { name: 'Open Trips', exact: true }).click();
  const listLink = page.getByRole('link', { name: new RegExp(title) });
  await expect(listLink).toContainText('Completed');
  await listLink.click();
  await expect(page).toHaveURL(detailUrl);
  await expect(page.locator('.trip-detail')).toContainText('Completed');
  await expect(page.locator('.trip-note-list')).toContainText('Notes remain collaborative after completion.');
});
